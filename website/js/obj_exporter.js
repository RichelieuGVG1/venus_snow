/**
 * Venus 3D Wavefront OBJ & MTL Exporter
 * -------------------------------------
 * Converts Three.js geometries into standard .obj + .mtl format
 * with preserved UVs (TEXCOORD_0), normals, and texture material references.
 *
 * Project: Venus — Metallic Snow & Surface Types
 * Author: Guryanov
 */

export class OBJExporter {
    /**
     * Parses a Three.js Object3D (Mesh or Group) into OBJ and MTL text.
     * @param {THREE.Object3D} object 
     * @param {string} [materialFileName='material.mtl']
     * @param {string} [textureFileName='']
     * @returns {{ obj: string, mtl: string }}
     */
    parse(object, materialFileName = 'material.mtl', textureFileName = '') {
        let output = '';
        let indexVertex = 0;
        let indexNormals = 0;
        let indexUvs = 0;

        output += '# Venus 3D Model OBJ Export\n';
        output += '# Generated by Venus 3D Interactive Atlas (Three.js Engine)\n';
        output += '# Author: Guryanov\n';
        output += `# Source: Magellan GxDR (NASA PDS Geosciences Node)\n`;
        if (materialFileName) {
            output += `mtllib ${materialFileName}\n\n`;
        }

        const mtlName = 'venus_surface_mat';

        object.traverse((child) => {
            if (!child.isMesh || !child.geometry) return;

            const geometry = child.geometry;
            const positions = geometry.getAttribute('position');
            const normals = geometry.getAttribute('normal');
            const uvs = geometry.getAttribute('uv');
            const indices = geometry.getIndex();

            const meshName = child.name || 'venus_mesh';
            output += `o ${meshName}\n`;
            output += `usemtl ${mtlName}\n`;
            output += `s 1\n`;

            // Vertices
            if (positions) {
                for (let i = 0; i < positions.count; i++) {
                    const x = positions.getX(i);
                    const y = positions.getY(i);
                    const z = positions.getZ(i);
                    output += `v ${x.toFixed(6)} ${y.toFixed(6)} ${z.toFixed(6)}\n`;
                }
            }

            // Texture UV coordinates
            if (uvs) {
                for (let i = 0; i < uvs.count; i++) {
                    const u = uvs.getX(i);
                    const v = uvs.getY(i);
                    // glTF UVs already conform to standard texture orientation
                    output += `vt ${u.toFixed(6)} ${v.toFixed(6)}\n`;
                }
            }

            // Normals
            if (normals) {
                for (let i = 0; i < normals.count; i++) {
                    const nx = normals.getX(i);
                    const ny = normals.getY(i);
                    const nz = normals.getZ(i);
                    output += `vn ${nx.toFixed(6)} ${ny.toFixed(6)} ${nz.toFixed(6)}\n`;
                }
            }

            // Faces
            if (indices) {
                for (let i = 0; i < indices.count; i += 3) {
                    const a = indices.getX(i) + 1 + indexVertex;
                    const b = indices.getX(i + 1) + 1 + indexVertex;
                    const c = indices.getX(i + 2) + 1 + indexVertex;

                    if (uvs && normals) {
                        const au = indices.getX(i) + 1 + indexUvs;
                        const bu = indices.getX(i + 1) + 1 + indexUvs;
                        const cu = indices.getX(i + 2) + 1 + indexUvs;
                        const an = indices.getX(i) + 1 + indexNormals;
                        const bn = indices.getX(i + 1) + 1 + indexNormals;
                        const cn = indices.getX(i + 2) + 1 + indexNormals;
                        output += `f ${a}/${au}/${an} ${b}/${bu}/${bn} ${c}/${cu}/${cn}\n`;
                    } else if (uvs) {
                        const au = indices.getX(i) + 1 + indexUvs;
                        const bu = indices.getX(i + 1) + 1 + indexUvs;
                        const cu = indices.getX(i + 2) + 1 + indexUvs;
                        output += `f ${a}/${au} ${b}/${bu} ${c}/${cu}\n`;
                    } else if (normals) {
                        const an = indices.getX(i) + 1 + indexNormals;
                        const bn = indices.getX(i + 1) + 1 + indexNormals;
                        const cn = indices.getX(i + 2) + 1 + indexNormals;
                        output += `f ${a}//${an} ${b}//${bn} ${c}//${cn}\n`;
                    } else {
                        output += `f ${a} ${b} ${c}\n`;
                    }
                }
            } else if (positions) {
                for (let i = 0; i < positions.count; i += 3) {
                    const a = i + 1 + indexVertex;
                    const b = i + 2 + indexVertex;
                    const c = i + 3 + indexVertex;

                    if (uvs && normals) {
                        output += `f ${a}/${a}/${a} ${b}/${b}/${b} ${c}/${c}/${c}\n`;
                    } else if (uvs) {
                        output += `f ${a}/${a} ${b}/${b} ${c}/${c}\n`;
                    } else {
                        output += `f ${a} ${b} ${c}\n`;
                    }
                }
            }

            if (positions) indexVertex += positions.count;
            if (normals) indexNormals += normals.count;
            if (uvs) indexUvs += uvs.count;
        });

        // Generate corresponding MTL material string
        let mtlOutput = '# Venus 3D Material Definition\n';
        mtlOutput += `# Author: Guryanov\n\n`;
        mtlOutput += `newmtl ${mtlName}\n`;
        mtlOutput += `Ka 0.200000 0.200000 0.200000\n`;
        mtlOutput += `Kd 0.850000 0.850000 0.850000\n`;
        mtlOutput += `Ks 0.400000 0.400000 0.400000\n`;
        mtlOutput += `Ns 35.000000\n`;
        mtlOutput += `illum 2\n`;
        mtlOutput += `d 1.0\n`;
        if (textureFileName) {
            mtlOutput += `map_Kd ${textureFileName}\n`;
        }

        return { obj: output, mtl: mtlOutput };
    }

    /**
     * Helper to download generated text files in the browser.
     * @param {string} filename 
     * @param {string} content 
     * @param {string} [mimeType='text/plain']
     */
    static downloadFile(filename, content, mimeType = 'text/plain') {
        const blob = new Blob([content], { type: mimeType });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = filename;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        setTimeout(() => URL.revokeObjectURL(url), 2000);
    }
}

