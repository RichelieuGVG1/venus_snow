    row = {"регион": name, "пикселей": int(m.sum()), COL_MAX: float(np.nanmax(h)) if m.any() else np.nan,
           COL_HC: np.nan, COL_ERR: np.nan, "перепад Δe": np.nan, "e0 ниже линии": np.nan}
    fit = None
    if m.sum() > 200 and np.nanmax(h) > 2:
        try:
            p0 = [np.percentile(e, 70), 0.25, np.percentile(h, 90), 0.3]
            popt, pcov = curve_fit(sigmoid, h, e, p0=p0, maxfev=20000,
                                   bounds=([0.4, 0.0, -1, 0.03], [1.0, 0.8, 12, 3.0]))
            perr = np.sqrt(np.diag(pcov))
            #перепад меньше 0.05 не считается аномалией
            if popt[1] > 0.05 and popt[2] < np.nanmax(h):
                fit = popt
                row.update({COL_HC: popt[2], COL_ERR: perr[2], "перепад Δe": popt[1], "e0 ниже линии": popt[0]})
        except (RuntimeError, ValueError):
            pass
    b = binned(h, p) if m.any() else np.empty((0, 3))
    cross = np.where((b[:-1, 1] < 0.5) & (b[1:, 1] >= 0.5))[0] if len(b) > 1 else []
    row[COL_ML] = float(b[cross[0] + 1, 0]) if len(cross) else np.nan
