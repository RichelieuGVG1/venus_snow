def numeric_rows(path, n_min, n_max=None):  #прочитать строки из n_min–n_max чисел, текстовые строки отбросить
    rows, skipped = [], 0
    with open(path, "r", errors="ignore") as f:
        for line in f:
            t = [x for x in _tok.split(line.strip().strip('"')) if x]
            if not (n_min <= len(t) <= (n_max or n_min)):
                skipped += 1
                continue
            try:
                rows.append([float(x.strip('"')) for x in t])
            except ValueError:
                skipped += 1
    return np.array(rows), skipped


