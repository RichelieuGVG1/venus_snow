def sigmoid(h, e0, d, hc, w):  #рассчитать сигмоиду перепада излучательной способности
    return e0 - d / (1 + np.exp(-(h - hc) / w))


def binned(x, y, step=0.25, min_n=15):  #рассчитать медианы y в интервалах x
    bins = np.arange(np.floor(np.nanmin(x)), np.ceil(np.nanmax(x)) + step, step)
    out = [((a + b) / 2, np.median(y[(x >= a) & (x < b)]), ((x >= a) & (x < b)).sum())
           for a, b in zip(bins[:-1], bins[1:])]
    return np.array([o for o in out if o[2] >= min_n]).reshape(-1, 3)


