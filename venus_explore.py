def latlon_axes(res):  #вычислить центры пикселей: широта сверху вниз, долгота слева направо
    lat = 90.0 - (np.arange(int(round(180 / res))) + 0.5) * res
    lon = -180.0 + (np.arange(int(round(360 / res))) + 0.5) * res
    return lat, lon


def pixel_area_km2(lat, res):  #вычислить площадь пикселя по широте, км^2
    side = R_KM * np.deg2rad(res)
