def region_mask(lat, lon, box):  #построить маску региона
    la = (lat >= box["lat"][0]) & (lat <= box["lat"][1])
    lo = (lon >= box["lon"][0]) & (lon <= box["lon"][1])
    return la[:, None] & lo[None, :]


def region_slices(lat, lon, box):  #получить срезы строк и столбцов региона
    rows = np.where((lat >= box["lat"][0]) & (lat <= box["lat"][1]))[0]
    cols = np.where((lon >= box["lon"][0]) & (lon <= box["lon"][1]))[0]
    return slice(rows.min(), rows.max() + 1), slice(cols.min(), cols.max() + 1)


def fill_nan_nearest(a):  #заполнить nan (нечисловые значения) ближайшими значениями
    mask = ~np.isfinite(a)
    if not mask.any():
        return a
    idx = distance_transform_edt(mask, return_distances=False, return_indices=True)
    return a[tuple(idx)]


