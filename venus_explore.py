def _factor(name):  #рассчитать шаг прореживания региона
    rs, cs = region_data(name)
    return max(1, int(np.ceil(np.sqrt(LAT[rs].size * LON[cs].size / MAX_POINTS))))


def _region_arrays(name, layer, snow_source):  #получить прореженные массивы региона
    rs, cs = region_data(name)
    lat_r, lon_r = LAT[rs], LON[cs]
    f = _factor(name)
    cut = lambda a, cat=False: coarsen(a[rs, cs], f, cat)
    if f > 1:
        lat_r = lat_r[: (lat_r.size // f) * f].reshape(-1, f).mean(1)
        lon_r = lon_r[: (lon_r.size // f) * f].reshape(-1, f).mean(1)
    return (lat_r, lon_r, cut(ELEV_FILLED), cut(LAYERS[layer]["data"], LAYERS[layer].get("categorical", False)),
            cut(RES[snow_source]), cut(RES["elev_km"]))


def _aspect(lat_r, lon_r, elev, exag):  #рассчитать пропорции осей с учетом широты и преувеличения
    xk = (lon_r.max() - lon_r.min()) * KM_PER_DEG * np.cos(np.deg2rad(lat_r.mean()))
    yk = (lat_r.max() - lat_r.min()) * KM_PER_DEG
    zk = max(np.nanmax(elev) - np.nanmin(elev), 0.1) * exag
    m = max(xk, yk)
    return dict(x=xk / m, y=yk / m, z=max(zk / m, 0.02))


def _snow_offset(elev):  #рассчитать подъем слоя снега над рельефом, км
    return 0.02 + 0.01 * float(np.nanmax(elev) - np.nanmin(elev))


