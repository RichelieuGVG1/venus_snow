def region_stats(name, snow_source, thr, plane_level):  #рассчитать статистику региона
    rs, cs = region_data(name)
    snow, elev, emis = RES[snow_source][rs, cs], RES["elev_km"][rs, cs], RES["emis"][rs, cs]
    area, m = AREA[rs, cs], np.isfinite(elev)
    sm = m & (np.nan_to_num(snow) >= thr)
    hc = snowline_of(name)
    above = m & (elev >= plane_level) if plane_level is not None else m & False
    return {
        "регион": proper_name(name),
        "максимальная высота": f"{np.nanmax(elev):.2f} км",
        "снеговая линия h_c (ячейка 6)": f"{hc:.2f} км" if hc else "не выделена",
        f"площадь снега при p >= {thr:.2f}": f"{area[sm].sum():,.0f} км^2",
        "доля региона под снегом": f"{100 * area[sm].sum() / max(area[m].sum(), 1):.2f} %",
        "площадь выше плоскости": f"{area[above].sum():,.0f} км^2" if plane_level is not None else "плоскость скрыта",
        "излучательная способность выше и ниже плоскости":
            f"{np.nanmean(emis[above]):.3f} и {np.nanmean(emis[m & ~above]):.3f}" if above.any() else "плоскость скрыта",
    }


