def proper_name(name):  #написать имя собственное с заглавных букв
    return re.sub(r"(^|[\s(])(\w)", lambda m: m.group(1) + m.group(2).upper(), name)


def text_case(s):  #перевести подпись в нижний регистр с сохранением имен собственных
    s = s.lower()
    for low, up in PROPER_WORDS.items():
        s = re.sub(rf"\b{low}\b", up, s)
    return s


