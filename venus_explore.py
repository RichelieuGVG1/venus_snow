def mc_model(eps_complex, theta_deg, psi_deg):  #рассчитать модельную долю круговой поляризации отраженной волны
    th, ps = np.deg2rad(theta_deg), np.deg2rad(psi_deg)
    k = np.sqrt(eps_complex - np.sin(th) ** 2)
    Rh = (np.cos(th) - k) / (np.cos(th) + k)
    Rv = (eps_complex * np.cos(th) - k) / (eps_complex * np.cos(th) + k)
    Eh, Ev = Rh * np.cos(ps), Rv * np.sin(ps)
    return np.abs(2 * np.imag(np.conj(Eh) * Ev)) / (np.abs(Eh) ** 2 + np.abs(Ev) ** 2)


