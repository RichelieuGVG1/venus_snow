class ClusterModel:  #привести алгоритмы к единому интерфейсу fit и predict, перенос через knn (k ближайших соседей)
    SMALL = {"Agglomerative", "HDBSCAN"}

    def __init__(self, algo, k=None, param=None, seed=0):  #сохранить параметры конфигурации
        self.algo, self.k, self.param, self.seed = algo, k, param, seed
        self.knn, self.noise_frac = None, 0.0

    def _build(self):  #создать модель алгоритма
        a, k, s = self.algo, self.k, self.seed
        if a == "KMeans":
            return KMeans(n_clusters=k, n_init=10, random_state=s)
        if a == "GMM":
            return GaussianMixture(n_components=k, covariance_type="full", n_init=2, random_state=s)
        if a == "BayesGMM":
            return BayesianGaussianMixture(n_components=k, weight_concentration_prior_type="dirichlet_process",
                                           weight_concentration_prior=0.1, max_iter=500, random_state=s)
        if a == "Birch":
            return Birch(n_clusters=k, threshold=0.5)
        if a == "Agglomerative":
            return AgglomerativeClustering(n_clusters=k, linkage="ward")
        if a == "HDBSCAN":
            return HDBSCAN(min_cluster_size=self.param, min_samples=10)
        raise ValueError(a)

    def fit(self, X):  #обучить модель
        if self.algo in self.SMALL:
            X = X[: CFG["n_small"]]
        m = self._build()
        if self.algo in self.SMALL:
            lab = m.fit_predict(X)
            keep = lab >= 0
            self.noise_frac = 1 - keep.mean()
            if len(np.unique(lab[keep])) >= 2:
                self.knn = KNeighborsClassifier(n_neighbors=15, n_jobs=-1).fit(X[keep], lab[keep])
        else:
            m.fit(X)
        self.model = m
        return self

    def predict(self, X):  #разметить новые точки
        if self.algo in self.SMALL:
            return self.knn.predict(X) if self.knn is not None else np.zeros(len(X), int)
        return self.model.predict(X)

    @property
    def name(self):  #получить название конфигурации
        return f"{self.algo}, k={self.k}" if self.k else f"{self.algo}, мин. размер {self.param}"


def evaluate(model_a, model_b, X):  #рассчитать метрики качества разбиения
    lab = model_a.predict(X)
    _, lab = np.unique(lab, return_inverse=True)
    n = lab.max() + 1
    row = {"algo": model_a.algo, "k": model_a.k, "param": model_a.param, "config": model_a.name,
           "n_clusters": int(n), "noise_frac": round(model_a.noise_frac, 3)}
    shares = np.bincount(lab) / len(lab)
    row["max_share"], row["min_share"] = shares.max(), shares.min()
    if n < 2:
        return row
    row["silhouette"] = silhouette_score(X, lab, sample_size=min(5000, len(X)), random_state=seed)
    row["calinski_harabasz"] = calinski_harabasz_score(X, lab)
    row["davies_bouldin"] = davies_bouldin_score(X, lab)
    if model_b is not None:
        row["stability_ari"] = adjusted_rand_score(lab, model_b.predict(X))
    return row


