def analyse_orbit(df):  #рассчитать мощность эха, шум, snr (отношение сигнал/шум) и поляризацию каждого шага
    nbin = int(df["bin"].nunique())
    f = df["f"].values[:nbin]
    PR = df["pr"].values.reshape(-1, nbin)
    PL = df["pl"].values.reshape(-1, nbin)
    C = (df["cm"].values * np.exp(1j * df["cp"].values)).reshape(-1, nbin)
    t = df.groupby("n", sort=False)["t"].first().values
    noise_m = np.zeros(len(f), bool)
    for a, b in BSR["noise_bands_hz"]:
        noise_m |= (f >= a) & (f <= b)
    nR, nL = np.median(PR[:, noise_m], 1), np.median(PL[:, noise_m], 1)
    sR = 1.4826 * np.median(np.abs(PR[:, noise_m] - nR[:, None]), 1)
    sL = 1.4826 * np.median(np.abs(PL[:, noise_m] - nL[:, None]), 1)
    exc = (PR - nR[:, None]) + (PL - nL[:, None])
    #окно эха: по 20% самых сильных шагов, где средний избыток выше 10% пика
    srch = (f >= BSR["echo_search_hz"][0]) & (f <= BSR["echo_search_hz"][1])
    strong = np.argsort(exc[:, srch].sum(1))[-max(3, len(t) // 5):]
    prof = np.array(pd.Series(exc[strong].mean(0)).rolling(5, center=True, min_periods=1).mean().values, copy=True)
    prof[~srch] = 0
    pk = int(np.argmax(prof))
    lo = hi = pk
    while lo > 0 and prof[lo - 1] > 0.1 * prof[pk]:
        lo -= 1
    while hi < len(f) - 1 and prof[hi + 1] > 0.1 * prof[pk]:
        hi += 1
    win = slice(lo, hi + 1)
    nw = hi - lo + 1
    ER = (PR[:, win] - nR[:, None]).sum(1)
    EL = (PL[:, win] - nL[:, None]).sum(1)
    X = C[:, win].sum(1)
    tot = ER + EL
    snr = tot / (np.sqrt(sR ** 2 + sL ** 2) * np.sqrt(nw) + 1e-30)
    fw = f[win]
    w = np.clip(exc[:, win], 0, None)
    cen = (w * fw).sum(1) / (w.sum(1) + 1e-30)
    width = np.sqrt((w * (fw - cen[:, None]) ** 2).sum(1) / (w.sum(1) + 1e-30))
    #узкий всплеск в одном бине считается помехой
    spike = (w.max(1) / (w.sum(1) + 1e-30)) > 0.5
    out = pd.DataFrame({"t": t, "echo_R": ER, "echo_L": EL, "snr": snr,
                        "m_c": np.abs(ER - EL) / np.where(tot > 0, tot, np.nan),
                        "m_l": 2 * np.abs(X) / np.where(tot > 0, tot, np.nan),
                        "doppler_width_hz": width, "interference": spike})
    return out, (f, PR + PL, (f[lo], f[hi]), noise_m)


