def grid_faces(nr, nc):
    """Треугольники для регулярной сетки nr×nc (строки — с севера на юг, столбцы — с запада на восток)."""
    i, j = np.meshgrid(np.arange(nr - 1), np.arange(nc - 1), indexing="ij")
    a = (i * nc + j).ravel()
    b, c, d = a + nc, a + 1, a + nc + 1
    return np.concatenate([np.stack([a, b, c], 1), np.stack([c, b, d], 1)])


