def _download(url, dst):  #загрузить файл, если его нет
    if dst.exists() and dst.stat().st_size > 0:
        print(f"   уже загружен: {dst.name}")
        return
    with requests.get(url, stream=True, timeout=120) as r:
        r.raise_for_status()
        tmp = dst.with_name(dst.name + ".part")
        with open(tmp, "wb") as f, tqdm(total=int(r.headers.get("content-length", 0)), unit="B",
                                        unit_scale=True, desc=dst.name) as bar:
            for ch in r.iter_content(1 << 20):
                f.write(ch)
                bar.update(len(ch))
        tmp.rename(dst)


