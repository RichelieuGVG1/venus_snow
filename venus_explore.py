from scipy.ndimage import uniform_filter

ENVI_DTYPES = {1: np.uint8, 2: np.int16, 3: np.int32, 4: np.float32,
               5: np.float64, 12: np.uint16, 13: np.uint32}


def parse_envi_hdr(path):  #разобрать заголовок ENVI (среда визуализации изображений)
    text = Path(path).read_text(errors="ignore")
    hdr = {}
    for m in re.finditer(r"^\s*([A-Za-z][^=\n]*?)\s*=\s*(\{.*?\}|[^\n]*)", text, flags=re.M | re.S):
        hdr[m.group(1).strip().lower()] = m.group(2).strip().strip("{}").strip()
    return hdr


def read_product(key, stem):  #прочитать массив и перевести в физические единицы
    p = PRODUCTS[key]
    hdr = parse_envi_hdr(DATA_DIR / f"{stem}.hdr")
    L, S = int(hdr["lines"]), int(hdr["samples"])
    dtype = np.dtype(ENVI_DTYPES[int(hdr.get("data type", 12))])
    offset = int(hdr.get("header offset", 0))
    bo_hdr = int(hdr.get("byte order", 0))
    orders = [bo_hdr, 1 - bo_hdr] if dtype.itemsize > 1 else [bo_hdr]

    #порядок байтов подтверждается правдоподобием медианы в физических единицах
    for bo in orders:
        dt = dtype.newbyteorder("<" if bo == 0 else ">")
        stored = np.fromfile(DATA_DIR / f"{stem}.img", dtype=dt, count=L * S, offset=offset).reshape(L, S)
        sub = stored[::7, ::7].astype(np.float64)
        sub = sub[sub > 0] * p["scale"] + p["offset"]
        med = float(np.median(sub)) if sub.size else np.nan
        if p["plaus"][0] <= med <= p["plaus"][1]:
            break
        print(f"   {key}: медиана {med:.4g} неправдоподобна при порядке байтов {bo}, проверка альтернативного порядка")
    else:
        print(f"   {key}: ни один порядок байтов не дал правдоподобных значений, требуется проверка файла")

    valid = stored > 0
    phys = np.full((L, S), np.nan, dtype=np.float32)
    if key == "topo":
        phys[valid] = ((stored[valid].astype(np.float64) * p["scale"] + p["offset"]
                        - CFG["venus_radius_m"]) / 1000.0).astype(np.float32)
    else:
        phys[valid] = (stored[valid].astype(np.float64) * p["scale"] + p["offset"]).astype(np.float32)
    return phys, hdr


def nan_box_smooth(img, k):  #сгладить окном k*k с учетом пропущенных значений
    if k <= 1:
        return img
    m = np.isfinite(img).astype(np.float32)
    v = np.where(m > 0, img, 0).astype(np.float32)
    num, den = uniform_filter(v, k), uniform_filter(m, k)
    return np.where(den > 0.5, num / np.maximum(den, 1e-6), np.nan).astype(np.float32)


def sinusoidal_to_latlon(img, res):  #перепроецировать синусоидальную сетку на сетку широты и долготы
    L, S = img.shape
    R = CFG["venus_radius_m"]
    pix_m = 2 * np.pi * R / S
    dlat_src = 180.0 / L
    img = nan_box_smooth(img, max(1, int(round(res / dlat_src))))
    lat, lon = latlon_axes(res)
    LAT, LON = np.meshgrid(lat, lon, indexing="ij")
    row = np.floor((90.0 - LAT) / dlat_src).astype(np.int64)
    x_m = np.deg2rad(LON) * R * np.cos(np.deg2rad(LAT))
    col = np.floor(x_m / pix_m + S / 2).astype(np.int64)
    ok = (row >= 0) & (row < L) & (col >= 0) & (col < S)
    out = np.full(LAT.shape, np.nan, dtype=np.float32)
    out[ok] = img[row[ok], col[ok]]
    return out


