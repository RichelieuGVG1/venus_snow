def remote_listing(url):  #получить список файлов каталога на сервере
    r = requests.get(url, timeout=60)
    r.raise_for_status()
    hrefs = re.findall(r'href="([^"]+)"', r.text, flags=re.I)
    return sorted({h.rstrip("/").split("/")[-1] for h in hrefs})


def remote_product_names():  #найти имена файлов продуктов на сервере, при ошибке проверить типовые имена
    try:
        names = remote_listing(CFG["base_url"])
        print(f"   файлов в каталоге на сервере: {len(names)}")
    except Exception as e:
        print(f"   листинг каталога недоступен ({str(e).lower()}), проверка типовых имен")
        names = []
    found = {}
    for key, p in PRODUCTS.items():
        cands = [n[:-4] for n in names
                 if n.lower().startswith(p["prefix"]) and n.lower().endswith(".img") and "error" not in n.lower()]
        if cands:
            found[key] = cands[0]
            continue
        for suffix in ("sinu", "sinus", "sin"):
            stem = p["prefix"] + suffix
            try:
                if requests.head(CFG["base_url"] + stem + ".img", timeout=30).status_code == 200:
                    found[key] = stem
                    break
            except requests.RequestException:
                pass
    return found


def download(url, dst, required=True, retries=3):  #загрузить файл с повторными попытками
    if dst.exists() and dst.stat().st_size > 0:
        print(f"   уже загружен: {dst.name}")
        return True
    tmp = dst.with_name(dst.name + ".part")
    for attempt in range(1, retries + 1):
        try:
            with requests.get(url, stream=True, timeout=120) as r:
                r.raise_for_status()
                total = int(r.headers.get("content-length", 0))
                with open(tmp, "wb") as f, tqdm(total=total, unit="B", unit_scale=True, desc=dst.name) as bar:
                    for chunk in r.iter_content(chunk_size=1 << 20):
                        f.write(chunk)
                        bar.update(len(chunk))
            tmp.rename(dst)
            return True
        except Exception as e:
            print(f"   {dst.name}: попытка {attempt}/{retries} не удалась ({str(e).lower()})")
            time.sleep(3 * attempt)
    if required:
        raise RuntimeError(f"не удалось загрузить {url}")
    return False


