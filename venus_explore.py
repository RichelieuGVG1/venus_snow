def _b64(arr):  #закодировать массив в base64 (текстовая кодировка двоичных данных)
    return base64.b64encode(np.ascontiguousarray(arr).tobytes()).decode("ascii")


def _quant8(a, lo, hi):  #упаковать значения в uint8 (беззнаковое 8-битное целое), 255 – нет данных
    q = np.round((np.clip(a, lo, hi) - lo) / max(hi - lo, 1e-9) * 254)
    return np.where(np.isfinite(a), q, 255).astype(np.uint8)


def region_payload(name):  #подготовить данные региона для html-копии
    rs, cs = region_data(name)
    f = _factor(name)
    lat_r, lon_r, elev, *_ = _region_arrays(name, "elev", "snow_prob")
    emin, emax = float(np.nanmin(elev)), float(np.nanmax(elev))
    raw = coarsen(RES["elev_km"][rs, cs], f)
    area = coarsen(AREA[rs, cs], f) * f * f
    p = {"label": proper_name(name), "lat": lat_r.round(4).tolist(), "lon": lon_r.round(4).tolist(),
         "nr": int(elev.shape[0]), "nc": int(elev.shape[1]), "emin": emin, "emax": emax,
         "elev": _b64(np.round((elev - emin) / max(emax - emin, 1e-9) * 65535).astype("<u2")),
         "valid": _b64(np.isfinite(raw).astype(np.uint8)),
         "area": _b64(np.nan_to_num(area).astype("<f4")),
         "emis": _b64(_quant8(coarsen(RES["emis"][rs, cs], f), 0.0, 1.0)),
         "snowline": snowline_of(name), "layers": {}, "snow": {}}
    for k, L in LAYERS.items():
        cat = L.get("categorical", False)
        d = coarsen(L["data"][rs, cs], f, cat)
        p["layers"][k] = _b64(np.where(np.isfinite(d), np.clip(np.nan_to_num(d), 0, 254), 255).astype(np.uint8)
                              if cat else _quant8(d, *L["range"]))
    for src in SNOW_SOURCES.values():
        p["snow"][src] = _b64(_quant8(coarsen(RES[src][rs, cs], f), 0.0, 1.0))
    return p


